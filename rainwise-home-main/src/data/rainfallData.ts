// Get rainfall by location name
export const getRainfallByLocation = (locationName: string): number | null => {
  const location = locationRainfallData.find(
    loc => loc.name.toLowerCase() === locationName.toLowerCase() || 
           loc.displayName.toLowerCase() === locationName.toLowerCase()
  );
  return location?.annualRainfall ?? null;
};
